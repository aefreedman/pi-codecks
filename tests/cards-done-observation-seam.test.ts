  assert.deepEqual(observations[0].card, { cardId: 'c', accountSeq: 0, title: null, status: false, derivedStatus: null, visibility: '', effort: 0, sprintId: null });
  assert.deepEqual(observations[0].transition, { from: null, to: ' DONE ' });
  assert.equal(observations[0].activity.createdAt, '2026-04-28T01:00:00+00:00');
  assert.equal(observations[0].event.doneAt, '2026-04-28T01:00:00.000Z');
  assert.equal(observations[0].event.title, '(untitled)');
  assert.equal(observations[0].relations.changer, 'unresolved');
  assert.equal(observations[0].relations.assignee, 'null');
  assert.equal(observations[0].relations.deck, 'unresolved');
  assert.equal(observations[0].assignee, null);
  assert.equal(observations[0].changer, undefined);
