useInertEnvironmentCredentialProvider();
const original = globalThis.fetch;
const requests: unknown[] = [];
let fail = false;
let failOffset: number | undefined;
let cardFields: Record<string, unknown> = { cardId: 'c', accountSeq: 0, title: null, status: false, derivedStatus: null, visibility: '', effort: 0, sprintId: null, assignee: null, deck: 'unresolved' };
